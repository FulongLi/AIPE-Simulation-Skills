"""Generate ngspice netlists for the DAB Level 1 (ideal) and Level 2 (behavioural) models.

Netlist topology (see package docstring for conventions)::

    V1 p_pos 0  ──┬── VsS1 ─ S1/D1 ─ a ─ VsS2 ─ S2/D2 ─ 0
                  └── VsS3 ─ S3/D3 ─ b ─ VsS4 ─ S4/D4 ─ 0
    a ─ Lext ─ Rsp ─ Llkp ─ tp      (series path, primary)
    tp ─ Lm ─ b                      (magnetising inductance)
    ideal transformer tp,b : ts0,d  (E/F sources, ratio n)
    ts0 ─ Vis ─ ts ─ Llks ─ Rss ─ c  (series path, secondary)
    V2 s_pos 0  ──┬── VsS5 ─ S5/D5 ─ c ─ VsS6 ─ S6/D6 ─ 0
                  └── VsS7 ─ S7/D7 ─ d ─ VsS8 ─ S8/D8 ─ 0

Zero-volt sources ``VsSk`` measure each switch-pair current (positive from
drain to source). ``Vis`` measures the secondary current leaving the
transformer. Level 2 adds dead time, linear ``Coss``, DC-link capacitors with
ESR/ESL and optional source impedance, and an RC-load port model.
"""

from __future__ import annotations

import json
import math

from .gating import SpsTiming, SWITCHES, HIGH_SIDE, LEG_OF
from .spec import DabCircuitSpec

# drain node, source node per switch (before inserting sense sources)
_SWITCH_NODES = {
    "S1": ("p_pos", "a"), "S2": ("a", "0"), "S3": ("p_pos", "b"), "S4": ("b", "0"),
    "S5": ("s_pos", "c"), "S6": ("c", "0"), "S7": ("s_pos", "d"), "S8": ("d", "0"),
}

SAVED_VECTORS = [
    "v(a)", "v(b)", "v(c)", "v(d)", "v(p_pos)", "v(s_pos)", "v(tp)", "v(ts)", "v(x1)",
    "i(Lext)", "i(Lm)", "i(Vis)", "i(V1)", "i(V2)",
    *[f"i(Vs{s})" for s in SWITCHES],
    *[f"v(g{s[1]})" for s in SWITCHES],
]



def _damping(explicit: float, inductance: float, c_oss: float) -> float:
    """Parallel damping resistance for a parasitic inductor (explicit value, or sqrt(L/C) automatic)."""
    if explicit > 0:
        return explicit
    c_ref = c_oss if c_oss > 0 else 1e-10
    return max(math.sqrt(max(inductance, 1e-12) / c_ref), 1e-3)


def _decoupling(add, prefix: str, node: str, capacitance: float, esr: float, esl: float, v_init: float, c_oss: float) -> None:
    """Local decoupling branch node -> ESR -> (ESL || damping) -> C -> 0, pre-charged to the bus voltage."""
    if capacitance <= 0:
        return
    n = node
    if esr > 0:
        add(f"Rloc{prefix} {n} loc{prefix}x {_fmt(esr)}")
        n = f"loc{prefix}x"
    if esl > 0:
        add(f"Lloc{prefix} {n} loc{prefix}y {_fmt(esl)}")
        add(f"Rlocd{prefix} {n} loc{prefix}y {_fmt(_damping(0.0, esl, c_oss))}")
        n = f"loc{prefix}y"
    add(f"Cloc{prefix} {n} 0 {_fmt(capacitance)} IC={_fmt(v_init)}")


def _fmt(value: float) -> str:
    return f"{value:.12g}"


def build_dab_netlist(spec: DabCircuitSpec) -> str:
    """Return the complete ngspice netlist text for ``spec``."""
    problems = spec.validate()
    if problems:
        raise ValueError("invalid DAB specification: " + "; ".join(problems))
    timing = SpsTiming(spec.f_sw, spec.phi_rad, spec.dead_time, spec.switch.gate_voltage, spec.switch.gate_rise_fall)
    sw = spec.switch
    lines: list[str] = []
    add = lines.append
    add(f"* AIPE DAB switching model level {spec.level}: {spec.name}")
    add("* Generated by aipe_simulation.dab.netlist (AIPE-Simulation-Skills). Units: SI.")
    add(f"* spec_sha256={spec.sha256()}")
    add("* Conventions: v_ab=v(a)-v(b); v_cd=v(c)-v(d); i_L=i(Lext) from a towards transformer;")
    add("*   i_s=i(Vis) out of transformer secondary into node c; i_dc1=-i(V1); i_dc2=i(V2);")
    add("*   i(VsSk) positive = drain-to-source conduction; phi>0 => secondary lags, P: port1->port2;")
    add("*   t=0 is the centre of the primary positive half-cycle (S1,S4 on).")
    for key, value in timing.describe().items():
        if key != "gate_pulses" and key != "switch_roles":
            add(f"* timing.{key} = {value}")
    add("* spec_json=" + spec.canonical_json())
    add("")
    # ---- DC ports -----------------------------------------------------------
    add("* ---- DC port 1 (source side)")
    dl1 = spec.dc_link1
    if dl1.capacitance > 0 or dl1.source_resistance > 0 or dl1.source_inductance > 0:
        # Zero-valued parasitics are omitted (direct connection): placeholder picohenry inductors in series
        # with milliohm resistors create femtosecond time constants that no transient solver can resolve.
        add(f"V1 src1 0 DC {_fmt(spec.v1)}")
        node = "src1"
        if dl1.source_resistance > 0:
            add(f"Rsrc1 {node} src1b {_fmt(dl1.source_resistance)}")
            node = "src1b"
        if dl1.source_inductance > 0:
            add(f"Lsrc1 {node} p_pos {_fmt(dl1.source_inductance)}")
            add(f"Rsrcd1 {node} p_pos {_fmt(_damping(dl1.source_damping_resistance, dl1.source_inductance, sw.c_oss))}")
        else:
            add(f"Vsrc1 {node} p_pos DC 0")
        if dl1.capacitance > 0:
            # The link capacitor starts at the bus voltage (uic): a 0 V start would be a bus pre-charge transient.
            node = "p_pos"
            if dl1.esr > 0:
                add(f"Resr1 p_pos cdc1x {_fmt(dl1.esr)}")
                node = "cdc1x"
            if dl1.esl > 0:
                add(f"Lesl1 {node} cdc1y {_fmt(dl1.esl)}")
                add(f"Resld1 {node} cdc1y {_fmt(_damping(dl1.esl_damping_resistance, dl1.esl, sw.c_oss))}")
                node = "cdc1y"
            add(f"Cdc1 {node} 0 {_fmt(dl1.capacitance)} IC={_fmt(spec.v1)}")
        _decoupling(add, "1", "p_pos", dl1.local_decoupling_capacitance, dl1.local_decoupling_esr, dl1.local_decoupling_esl, spec.v1, sw.c_oss)
    else:
        add(f"V1 p_pos 0 DC {_fmt(spec.v1)}")
    add("")
    add("* ---- DC port 2 (bidirectional port)")
    if spec.port2.type == "voltage_source":
        add(f"V2 s_pos 0 DC {_fmt(spec.v2)}")
    else:
        v_init = spec.port2.initial_voltage if spec.port2.initial_voltage is not None else spec.v2
        node = "s_pos"
        if spec.port2.esr > 0:
            add(f"Resr2 s_pos c2x {_fmt(spec.port2.esr)}")
            node = "c2x"
        if spec.port2.esl > 0:
            add(f"Lesl2 {node} c2y {_fmt(spec.port2.esl)}")
            add(f"Resld2 {node} c2y {_fmt(_damping(spec.port2.esl_damping_resistance, spec.port2.esl, sw.c_oss))}")
            node = "c2y"
        add(f"C2 {node} 0 {_fmt(spec.port2.capacitance)} IC={_fmt(v_init)}")
        _decoupling(add, "2", "s_pos", spec.port2.local_decoupling_capacitance, spec.port2.local_decoupling_esr, spec.port2.local_decoupling_esl, v_init, sw.c_oss)
        add("* V2 is a 0 V sense source in series with the load so that i(V2) is the load current")
        add(f"Rload2 s_pos ld2 {_fmt(spec.port2.load_resistance)}")
        add("V2 ld2 0 DC 0")
    if spec.dc_link2.capacitance > 0 and spec.port2.type == "voltage_source":
        dl2 = spec.dc_link2
        node = "s_pos"
        if dl2.esr > 0:
            add(f"Resr2b s_pos cdc2x {_fmt(dl2.esr)}")
            node = "cdc2x"
        if dl2.esl > 0:
            add(f"Lesl2b {node} cdc2y {_fmt(dl2.esl)}")
            add(f"Resld2b {node} cdc2y {_fmt(_damping(dl2.esl_damping_resistance, dl2.esl, sw.c_oss))}")
            node = "cdc2y"
        add(f"Cdc2 {node} 0 {_fmt(dl2.capacitance)} IC={_fmt(spec.v2)}")
        _decoupling(add, "2b", "s_pos", dl2.local_decoupling_capacitance, dl2.local_decoupling_esr, dl2.local_decoupling_esl, spec.v2, sw.c_oss)
    add("")
    # ---- bridges ------------------------------------------------------------
    vt = sw.gate_voltage / 2
    add(f"* ---- Switches ({spec.switch_model} channel model) + antiparallel diode (+ optional linear Coss), with 0 V current sense")
    for s in SWITCHES:
        drain, source = _SWITCH_NODES[s]
        sense = f"{drain}_{s.lower()}"
        gate = f"g{s[1]}"
        add(f"Vs{s} {drain} {sense} DC 0")
        if spec.switch_model == "behavioural":
            # C1-continuous smoothstep of the gate voltage that is exactly 0 below Vt - w and exactly 1 above
            # Vt + w (a tanh tail would leave a residual off-conductance of Gon * 1e-4 and dissipate kilowatts).
            g_on, g_off = 1.0 / sw.r_on, 1.0 / sw.r_off
            w = sw.transition_voltage
            tt = f"min(max((V({gate})-{_fmt(vt - w)})/{_fmt(2 * w)},0),1)"
            add(f"B{s} {sense} {source} I=V({sense},{source})*({_fmt(g_on)}*({tt})*({tt})*(3-2*({tt}))+{_fmt(g_off)})")
        else:
            add(f"{s} {sense} {source} {gate} 0 swmod")
        add(f"D{s[1]} {source} {sense} dmod")
        if sw.c_oss > 0:
            add(f"Coss{s[1]} {sense} cossx{s[1]} {_fmt(sw.c_oss)}")
            add(f"Rcoss{s[1]} cossx{s[1]} {source} {_fmt(max(sw.c_oss_esr, 1e-3))}")
        if sw.snubber_c > 0:
            add(f"Csn{s[1]} {sense} sn{s[1]} {_fmt(sw.snubber_c)}")
            add(f"Rsn{s[1]} sn{s[1]} {source} {_fmt(max(sw.snubber_r, 1e-3))}")
    add("")
    add("* ---- Gate signals (ideal, referenced to ground)")
    for s in SWITCHES:
        add(f"Vg{s[1]} g{s[1]} 0 {timing.gate_pulse(s).spice()}")
    add("")
    # ---- series path and transformer ---------------------------------------
    add("* ---- Series path (primary side): external inductance, resistance, leakage")
    ic_l = ""
    if spec.sim.initial_series_current is not None:
        ic_l = f" IC={_fmt(spec.sim.initial_series_current)}"
    add(f"Lext a x1 {_fmt(spec.l_ext)}{ic_l}")
    add(f"Rsp x1 x2 {_fmt(max(spec.r_series_p, 1e-6))}")
    # Series inductors must start with a consistent current (uic): a leakage inductor left at 0 A while the
    # external inductor starts at i_L(0) would create an impulsive start-up transient.
    if spec.l_lk_p > 0:
        add(f"Llkp x2 tp {_fmt(spec.l_lk_p)}{ic_l}")
    else:
        add("Vlkp x2 tp DC 0")
    add("")
    add(f"* ---- Ideal transformer n = Np/Ns = {_fmt(spec.n_ratio)} with magnetising inductance (primary referred)")
    if spec.sim.initial_magnetising_current is not None:
        ic_m = spec.sim.initial_magnetising_current
    elif spec.sim.initial_series_current is not None:
        ic_m = spec.periodic_magnetising_current_at_origin
    else:
        ic_m = 0.0
    add(f"Lm tp b {_fmt(spec.l_m)} IC={_fmt(ic_m)}")
    add(f"Esec ts0 d tp b {_fmt(1.0 / spec.n_ratio)}")
    add("Vis ts0 ts DC 0")
    add(f"Fpri tp b Vis {_fmt(1.0 / spec.n_ratio)}")
    add("")
    add("* ---- Series path (secondary side)")
    if spec.l_lk_s > 0:
        # Secondary current at t = 0: n * (i_L(0) - i_m(0)); i_m(0) is the magnetising initial current chosen above.
        ic_s = ""
        if spec.sim.initial_series_current is not None:
            ic_s = f" IC={_fmt(spec.n_ratio * (spec.sim.initial_series_current - ic_m))}"
        add(f"Llks ts x3 {_fmt(spec.l_lk_s)}{ic_s}")
    else:
        add("Vlks ts x3 DC 0")
    add(f"Rss x3 c {_fmt(max(spec.r_series_s, 1e-6))}")
    add("")
    # ---- models and analysis -----------------------------------------------
    vh = sw.gate_voltage / 10  # transition band Vt +/- Vh (3 V of a 15 V edge) for the sw model
    add("* ---- Device models")
    add(f".model swmod SW(Ron={_fmt(sw.r_on)} Roff={_fmt(sw.r_off)} Vt={_fmt(vt)} Vh={_fmt(vh)})")
    add(f".model dmod D(Is={_fmt(sw.d_is)} N={_fmt(sw.d_n)} Rs={_fmt(sw.d_rs)} Cjo={_fmt(sw.d_cjo)} Vj=0.7 M=0.5 Tt=0)")
    add("")
    add("* ---- Solver settings")
    add(f".options reltol={_fmt(spec.sim.reltol)} abstol={_fmt(spec.sim.abstol)} vntol={_fmt(spec.sim.vntol)} "
        f"chgtol={_fmt(spec.sim.chgtol)} method={spec.sim.method} maxord={spec.sim.maxord}")
    add(".options itl4=200 noinit")
    # The DC operating point of a switching converter with static gate states shorts the
    # inductors and transformer through milliohm paths and is physically meaningless, so the
    # transient always starts from stated initial conditions (zero unless IC= is given).
    add(f".tran {_fmt(spec.t_max)} {_fmt(spec.t_stop)} {_fmt(spec.t_output_start)} {_fmt(spec.t_max)} uic")
    add(".save " + " ".join(SAVED_VECTORS))
    add(".end")
    return "\n".join(lines) + "\n"


def saved_vectors() -> list[str]:
    return list(SAVED_VECTORS)


def switch_table() -> list[dict]:
    """Static description of the eight switches for downstream consumers."""
    return [{"id": s, "leg": LEG_OF[s], "side": "high" if s in HIGH_SIDE else "low",
             "bridge": "primary" if s in ("S1", "S2", "S3", "S4") else "secondary",
             "drain_node": _SWITCH_NODES[s][0], "source_node": _SWITCH_NODES[s][1],
             "current_vector": f"i(Vs{s})", "gate_vector": f"v(g{s[1]})"} for s in SWITCHES]


def netlist_metadata(spec: DabCircuitSpec) -> dict:
    timing = SpsTiming(spec.f_sw, spec.phi_rad, spec.dead_time, spec.switch.gate_voltage, spec.switch.gate_rise_fall)
    return {"spec": spec.to_dict(), "spec_sha256": spec.sha256(), "timing": timing.describe(),
            "switches": switch_table(), "saved_vectors": saved_vectors(),
            "t_max_s": spec.t_max, "t_stop_s": spec.t_stop, "t_output_start_s": spec.t_output_start,
            "l_total_primary_H": spec.l_total_primary, "v2_referred_V": spec.v2_referred}
